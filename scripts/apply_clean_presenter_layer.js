// Rebuild clean output
const output = [];
let i = 0;
while (i < lines.length) {
  const line = lines[i];

  // Global overflow hidden
  if (line.includes('html, body {')) {
    output.push('    html, body {');
    output.push('      overflow-x: hidden !important;');
    output.push('      max-width: 100vw !important;');
    i++;
    continue;
  }

  // Header responsive padding
  if (line.includes('class="no-print relative z-30 flex items-center justify-between px-8 py-3.5')) {
    output.push(line.replace('px-8 py-3.5', 'px-4 sm:px-8 py-3.5 overflow-hidden max-w-full'));
    i++;
    continue;
  }

  // Insert Slide 0 before Slide 1
  if (line.includes('<section id="slide-1"')) {
    output.push(...slide0Lines);
    output.push('    <section id="slide-1" class="slide flex-col justify-between">');
    i++;
    continue;
  }

  // Footer responsive padding
  if (line.includes('class="no-print relative z-30 flex items-center justify-between px-8 py-3')) {
    output.push(line.replace('px-8 py-3', 'px-4 sm:px-8 py-3 overflow-hidden max-w-full'));
    i++;
    continue;
  }

  // Script block replacement
  if (line.includes('<script>') && i > 1000) {
    output.push(...engineScriptLines);
    // Skip to end of old script block
    while (i < lines.length && !lines[i].includes('</script>')) {
      i++;
    }
    i++; // Skip </script>
    continue;
  }

  // Insert audio and caption widgets before </body>
  if (line.includes('</body>')) {
    output.push(...audioAndCaptionWidgetLines);
    output.push(line);
    i++;
    continue;
  }

  output.push(line);
  i++;
}

const finalHtml = output.join(isCRLF ? '\r\n' : '\n');
fs.writeFileSync('public/pitch/nhf/index.html', finalHtml, 'utf8');
console.log('Clean build written to public/pitch/nhf/index.html');
